package pctExerciciosMatrizes;

public class Ex02A {

	public static void main(String[] args) {

		        String[][] matriz = {
		            {"a", "b", "c", "d", "e"},
		            {"f", "g", "h", "i", "j"},
		            {"l", "m", "n", "o", "p"},
		            {"q", "r", "s", "t", "u"}
		        };

		        for (int lin = 0; lin < 4; lin++) {
		            for (int col = 0; col < 5; col++) {
		                System.out.print(matriz[lin][col] + " ");
		            }
		            System.out.println();
		        }
		    }
		}
	

	


